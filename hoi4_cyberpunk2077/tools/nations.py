# ---------------------------------------------------------------- награды
def cap(body):
    return "capital_scope = {\n" + indent(body, 1) + "\n}"


def PP(n): return f"add_political_power = {n}"
def ST(x): return f"add_stability = {x}"
def WS(x): return f"add_war_support = {x}"
def XP(n): return f"army_experience = {n}"
def MAN(n): return f"add_manpower = {n}"
def RS(): return "add_research_slot = 1"
def EQ(n): return f"add_equipment_to_stockpile = {{ type = infantry_equipment_1 amount = {n} }}"
def CIV(n): return cap(f"add_extra_state_shared_building_slots = {n}\nadd_building_construction = {{ type = industrial_complex level = {n} instant_build = yes }}")
def MIL(n): return cap(f"add_extra_state_shared_building_slots = {n}\nadd_building_construction = {{ type = arms_factory level = {n} instant_build = yes }}")
def DOCK(n): return cap(f"add_building_construction = {{ type = dockyard level = {n} instant_build = yes }}")
def AIR(n): return cap(f"add_building_construction = {{ type = air_base level = {n} instant_build = yes }}")
def RES_(kind, n): return cap(f"add_resource = {{ type = {kind} amount = {n} }}")
def TB(fid, cat, uses=2, bonus=1.0):
    key = loc("cp77_tooltips", f"cp77_tb_{fid}", "Технологический прорыв")
    return f"add_tech_bonus = {{ name = {key} bonus = {bonus} uses = {uses} category = {cat} }}"
def IDEA(i): return f"add_ideas = {i}"
def COS(t): return f"set_cosmetic_tag = {t}"
def GOV(party, elections="no"): return f"set_politics = {{ ruling_party = {party} elections_allowed = {elections} }}\nadd_popularity = {{ ideology = {party} popularity = 0.25 }}"
def NEWS(n): return f"every_country = {{ news_event = {{ id = cp77.{n} hours = 6 }} }}"
def J(*parts): return "\n".join(p for p in parts if p)


def WG(tag, kind="annex_everything"):
    return f"if = {{ limit = {{ country_exists = {tag} NOT = {{ has_war_with = {tag} }} NOT = {{ tag = {tag} }} }} create_wargoal = {{ type = {kind} target = {tag} }} }}"


def SUBJECT_OF(tag):
    return f"if = {{ limit = {{ country_exists = {tag} NOT = {{ has_war_with = {tag} }} }} {tag} = {{ puppet = ROOT }} }}"


def GUARANTEED_BY(tag):
    return f"if = {{ limit = {{ country_exists = {tag} NOT = {{ has_war_with = {tag} }} }} {tag} = {{ give_guarantee = ROOT }} }}"


def LEAD(tag, key, name, desc, color, ideology, kind="human", initials=""):
    return leader(name, f"{tag}_{key}_desc", desc, f"{tag.lower()}_{key}", color, ideology, kind, initials)


def SPIRIT(iid, name, desc, mods, icon):
    idea(iid, name, desc, mods, icon)
    return IDEA(iid)


def COSMETIC_TAG(key, name, adj, fl):
    COSMETIC[key] = (name, adj, fl)
    country_names(key, name, adj, None, fl)
    return COS(key)


NATIONS = {}


def nation(**d):
    NATIONS[d["tag"]] = d


