def decisions_for(n):
    """Возвращает (категория, [блоки решений])."""
    tag = n["tag"]
    cat = f"cp77_{tag.lower()}_category"
    loc("cp77_decisions", cat, n["name"] + ": государственные дела")
    loc("cp77_decisions", cat + "_desc", "Особые решения, доступные только этой державе.")
    blocks = []
    for key, name, desc, icon, cost, eff, reenable in n["decisions"]:
        did = f"cp77_{tag.lower()}_{key}"
        loc("cp77_decisions", did, name)
        loc("cp77_decisions", did + "_desc", desc)
        timing = f"days_re_enable = {reenable}" if reenable else "fire_only_once = yes"
        blocks.append((icon, f"{did} = {{\n\ticon = cp77_{icon}\n\tcost = {cost}\n\t{timing}\n"
                             f"\tcomplete_effect = {{\n{indent(eff, 2)}\n\t}}\n\tai_will_do = {{ factor = 1 }}\n}}"))
    return cat, f"tag = {tag}", blocks
