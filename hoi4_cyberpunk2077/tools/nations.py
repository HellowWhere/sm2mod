def build_tree(n):
    tag = n["tag"]
    T = Tree(f"cp77_{tag.lower()}_tree", f"cp77_focus_{tag.lower()}",
             f"country = {{\n\tfactor = 0\n\tmodifier = {{ add = 100 tag = {tag} }}\n}}")
    a = T.add
    icon, name, desc, rew = n["root"]
    root = a(f"{tag}_root", 4, 0, icon, name, desc, rew, filters=[POL])
    firsts = []
    for i, path in enumerate(n["paths"]):
        x = 1 + i * 3
        prev = root
        ai = [3, 2, 1][i]
        for j, (ic, nm, ds, rw) in enumerate(path):
            fid = a(f"{tag}_p{i}_{j}", x, j + 1, ic, nm, ds, rw, prereq=[prev], ai=ai if j == 0 else 1,
                    filters=[POL], cost=10 if j < 3 else 15)
            if j == 0:
                firsts.append(fid)
            prev = fid
    T.mutex_group(firsts)
    eco = n["eco"]
    pos = [(11, 0), (10, 1), (12, 1), (11, 2), (10, 3), (12, 3), (11, 4)]
    pre = [[], [0], [0], [(1, 2)], [3], [3], [4, 5]]
    for k, ((ic, nm, ds, rw), (x, y)) in enumerate(zip(eco, pos)):
        prs = []
        for p in pre[k]:
            prs.append(tuple(f"{tag}_eco_{q}" for q in p) if isinstance(p, tuple) else f"{tag}_eco_{p}")
        a(f"{tag}_eco_{k}", x, y, ic, nm, ds, rw, prereq=prs, filters=[IND])
    mil = n["mil"]
    pos = [(15, 0), (14, 1), (16, 1), (15, 2), (15, 3)]
    pre = [[], [0], [0], [(1, 2)], [3]]
    for k, ((ic, nm, ds, rw), (x, y)) in enumerate(zip(mil, pos)):
        prs = []
        for p in pre[k]:
            prs.append(tuple(f"{tag}_mil_{q}" for q in p) if isinstance(p, tuple) else f"{tag}_mil_{p}")
        a(f"{tag}_mil_{k}", x, y, ic, nm, ds, rw, prereq=prs, filters=[ARMY])
    return T


